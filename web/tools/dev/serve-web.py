#!/usr/bin/env python3
"""Local static server for the Animatix web demo with production-like serving:

- correct `application/wasm` MIME type (enables instantiateStreaming)
- transparent brotli negotiation: serves the precompressed `.br` twin when
  the client advertises `Accept-Encoding: br` (a CDN does the same)
- cache headers that keep the edit-and-reload loop working: generated engine
  artifacts (`.wasm`, `runtime/**.js`) are cacheable in production mode, while
  pages, stylesheets and `.amx` scene sources must be revalidated.
- `--no-cache` mode (default in local dev): sends no-cache headers for all
  resources so rebuilds and edits take effect immediately without clearing browser cache.
- integrity detection: verifies the SDK manifest and source identity at startup.

Usage:
  python3 web/tools/dev/serve-web.py [port] [root] [--host HOST] [--cache] [--no-cache]
  (default port 8124, host 127.0.0.1, serves web/, no-cache default)

  --host 0.0.0.0 exposes the server to the LAN/Tailscale; the default loopback
  binding is deliberately private.
"""
import argparse
import http.server
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

def find_default_web_dir():
    env_root = os.environ.get("SERVE_ROOT")
    if env_root and os.path.isdir(env_root):
        return os.path.abspath(env_root)

    # Check git root if available
    try:
        git_root = subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"],
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
        candidate = os.path.join(git_root, "web")
        if os.path.isdir(candidate):
            return candidate
    except Exception:
        pass

    script_dir = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.normpath(os.path.join(script_dir, "..", ".."))
    if os.path.isdir(candidate):
        return candidate

    if os.path.isdir("web"):
        return os.path.abspath("web")
    if os.path.isfile("index.html") and os.path.isdir("scenes"):
        return os.path.abspath(".")

    return os.path.abspath("web")


WEB_DIR = find_default_web_dir()
def normalize_base(value):
    """Only URL pathname prefixes, never filesystem paths or encoded segments."""
    if value in ("", "/"):
        return ""
    parts = value.strip("/").split("/")
    if not value.startswith("/") or any(not re.fullmatch(r"[A-Za-z0-9_-]+", p) for p in parts):
        raise ValueError("SERVE_BASE must be a simple absolute URL path prefix")
    return "/" + "/".join(parts)


SERVE_BASE = normalize_base(os.environ.get("SERVE_BASE", "/"))


def strip_base(path):
    if not SERVE_BASE:
        return path
    if path == SERVE_BASE or path.startswith(SERVE_BASE + "/"):
        return path[len(SERVE_BASE):] or "/"
    return None


REPO_ROOT = os.path.dirname(WEB_DIR) if os.path.basename(WEB_DIR) == "web" else os.path.abspath(".")

def repo_path(*parts):
    """Resolve *parts* under REPO_ROOT, or return None if the result escapes it."""
    for part in parts:
        path_part = Path(part)
        if path_part.is_absolute() or ".." in path_part.parts:
            return None
    root = Path(REPO_ROOT).resolve()
    candidate = Path(root, *parts).resolve()
    if not candidate.is_relative_to(root):
        return None
    return candidate


MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".wasm": "application/wasm",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".amx": "text/plain; charset=utf-8",
    ".ttf": "font/ttf",
    ".otf": "font/otf",
    ".gz": "application/gzip",
}

# Generated by web/tools/build/build-web.sh: expensive to rebuild, safe to cache in prod.
CACHEABLE = ".wasm"

NO_CACHE_MODE = True
WASM_STALENESS = None


def check_wasm_staleness(web_dir):
    """Verify the SDK by content identity when serving the source checkout."""
    sdk = os.path.join(web_dir, "runtime")
    if not os.path.isfile(os.path.join(sdk, "runtime-manifest.json")):
        return {"results": [("runtime", "missing", 0)]}
    # Nix may copy this script alone into /nix/store. Locate the checkout
    # from the served tree first; never assume __file__ retains repo depth.
    candidates = [Path(web_dir).resolve().parent, Path(REPO_ROOT).resolve(),
                  *Path(__file__).resolve().parents]
    repo_path = next((candidate for candidate in candidates
                      if (candidate / "Cargo.toml").is_file()
                      and (candidate / "web/tools/sdk.mjs").is_file()), None)
    if repo_path is None:
        return {"results": [("runtime", "stale", 0)]}
    repo = str(repo_path)
    args = ["node", os.path.join(repo, "web/tools/sdk.mjs"), "verify", sdk]
    if os.path.realpath(web_dir) == os.path.realpath(os.path.join(repo, "web")):
        args.append("--current")
    try:
        subprocess.run(args, cwd=repo, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        status = "fresh"
    except (OSError, subprocess.CalledProcessError):
        status = "stale"
    return {"results": [("runtime", status, 0)]}


def cache_control(path):
    if NO_CACHE_MODE:
        return "no-cache, no-store, must-revalidate"
    generated = (
        path.endswith(CACHEABLE)
        or "/runtime/" in path.replace(os.sep, "/")
        or path.endswith(".wasm.br")
        or "/fonts/" in path.replace(os.sep, "/")
        or path.endswith(".gz")
    )
    if generated:
        return "public, max-age=300"
    return "no-cache"


def example_library_path(path):
    if Path(WEB_DIR).resolve() != Path(REPO_ROOT, "web").resolve():
        return None
    prefix = "/examples/lib/"
    if not path.startswith(prefix):
        return None
    name = path[len(prefix):]
    if not re.fullmatch(r"[A-Za-z0-9_-]+\.amx", name):
        return None
    target = repo_path("examples", "lib", name)
    library = Path(REPO_ROOT, "examples", "lib").resolve()
    if target is None or not target.is_relative_to(library) or not target.is_file():
        return None
    return target


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=WEB_DIR, **kwargs)

    def guess_type(self, path):
        ext = os.path.splitext(path)[1].lower()
        return MIME.get(ext, "application/octet-stream")

    def translate_path(self, path):
        path = strip_base(path)
        if path is None:
            return os.path.join(WEB_DIR, "__rejected_path__")
        clean_path = unquote(path.split("?")[0].split("#")[0])
        if clean_path.startswith("/examples/lib/"):
            # Native example imports are available only on the development
            # server, never from a released/assembled site rooted elsewhere.
            target = example_library_path(clean_path)
            return str(target) if target is not None else os.path.join(WEB_DIR, "__rejected_path__")

        translated = super().translate_path(path)
        # Transparently serve web/embed/src/amx-player.js when embed/amx-player.js is requested,
        # so local dev does not require a prebuilt bundle and live edits take effect immediately.
        if translated.endswith(os.path.join("embed", "amx-player.js")):
            src_candidate = os.path.join(os.path.dirname(translated), "src", "amx-player.js")
            if os.path.isfile(src_candidate):
                if not os.path.exists(translated) or os.path.getmtime(src_candidate) > os.path.getmtime(translated):
                    return src_candidate
        return translated

    def do_GET(self):
        request_path = strip_base(self.path)
        if request_path is None:
            self.send_error(404, "Outside configured site base")
            return
        return super().do_GET()

    def send_head(self):
        # brotli negotiation: prefer the precompressed twin when present
        path = self.translate_path(self.path)
        accepts_br = "br" in self.headers.get("Accept-Encoding", "")
        if accepts_br and os.path.isfile(path) and not path.endswith(".br"):
            br_path = path + ".br"
            if os.path.isfile(br_path):
                # serve file.br with the original's type + Content-Encoding
                f = open(br_path, "rb")
                try:
                    self.send_response(200)
                    self.send_header("Content-Type", self.guess_type(path))
                    self.send_header("Content-Encoding", "br")
                    self.send_header("Content-Length", str(os.fstat(f.fileno()).st_size))
                    self.send_header("Vary", "Accept-Encoding")
                    self.end_headers()
                    return f
                except Exception:
                    f.close()
                    raise
        return super().send_head()

    def end_headers(self):
        self.send_header("Cache-Control", cache_control(self.translate_path(self.path)))
        # Attach staleness header if WASM artifacts are out-of-date
        if WASM_STALENESS and any(s == "stale" for _, s, _ in WASM_STALENESS["results"]):
            if "/runtime/" in self.path:
                self.send_header("X-Animatix-Wasm-Stale", "true")
        super().end_headers()

    def log_message(self, fmt, *args):
        sys.stderr.write("[serve-web] %s\n" % (fmt % args))


def print_staleness_banner(staleness):
    stale_items = [name for name, status, _ in staleness["results"] if status == "stale"]
    missing_items = [name for name, status, _ in staleness["results"] if status == "missing"]
    if not stale_items and not missing_items:
        return

    print("\n" + "=" * 72, file=sys.stderr)
    if missing_items:
        print("SDK is missing; run web/tools/build/ensure-web-pkg.sh --dev", file=sys.stderr)
    if stale_items:
        print("SDK verification failed or its source identity changed; rebuild it with web/tools/build/ensure-web-pkg.sh --dev", file=sys.stderr)
    print("=" * 72 + "\n", file=sys.stderr)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Animatix local web server")
    parser.add_argument("port", nargs="?", type=int, default=8124, help="Port (default: 8124)")
    parser.add_argument("root", nargs="?", type=str, default=None, help="Root directory (default: web/)")
    parser.add_argument("--host", default=os.environ.get("SERVE_HOST", "127.0.0.1"),
                        help="Bind address (default: 127.0.0.1; use 0.0.0.0 for Tailscale/LAN)")
    parser.add_argument("--cache", action="store_true", help="Enable 5-min caching for .wasm (production simulation)")
    parser.add_argument("--no-cache", action="store_true", help="Disable caching for all files (default)")

    args = parser.parse_args()

    port = args.port
    if args.root:
        if os.path.isdir(args.root):
            WEB_DIR = os.path.abspath(args.root)
        else:
            fallback = find_default_web_dir()
            WEB_DIR = fallback if os.path.isdir(fallback) else os.path.abspath(args.root)
    else:
        WEB_DIR = find_default_web_dir()

    # By default, use no-cache unless --cache is explicitly set
    NO_CACHE_MODE = not args.cache

    WASM_STALENESS = check_wasm_staleness(WEB_DIR)
    if WASM_STALENESS:
        print_staleness_banner(WASM_STALENESS)

    cache_desc = "disabled (live reload mode)" if NO_CACHE_MODE else "enabled (max-age=300 for wasm)"
    shown_host = "127.0.0.1" if args.host in ("", "0.0.0.0", "::") else args.host
    print(f"serving {WEB_DIR} at http://{shown_host}:{port}/ (bind {args.host}) [caching: {cache_desc}]")

    server = http.server.ThreadingHTTPServer((args.host, port), Handler)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
