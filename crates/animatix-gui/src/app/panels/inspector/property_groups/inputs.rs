use super::*;
use crate::app::design_tokens::spatial::Spatial;

mod fields;
mod variants;

pub(super) fn render_property_input(
    ui: &mut egui::Ui,
    entry: &PropertyEntry,
    input_rect: egui::Rect,
    theme: &eparts::Theme,
    sp: &Spatial,
    flat_style: &egui::Style,
    actor_label: &str,
    commands: &mut ActionQueue,
    keyframe_mode: bool,
    row_height: f32,
) {
    // ── Input widget (inside input_rect, no extra frame) ──
    match &entry.kind {
        PropertyKind::Vec2 { x, y } => fields::render_vec2_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            x,
            y,
        ),
        PropertyKind::Float(v) => fields::render_float_input(
            ui,
            entry,
            input_rect,
            theme,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            row_height,
            v,
        ),
        PropertyKind::U32(v) => fields::render_u32_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            v,
        ),
        PropertyKind::Bool(value) => fields::render_bool_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            value,
        ),
        PropertyKind::Color(rgba) => fields::render_color_input(
            ui,
            entry,
            input_rect,
            theme,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            rgba,
        ),
        PropertyKind::Enum { variants, value } => fields::render_enum_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            row_height,
            variants,
            value,
        ),
        PropertyKind::EnumOwned { variants, value } => fields::render_enum_owned_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            row_height,
            variants,
            value,
        ),
        PropertyKind::Sum { variants, value } => variants::render_sum_input(
            ui,
            entry,
            input_rect,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            variants,
            value,
        ),
        PropertyKind::Union { variants, value } => variants::render_union_input(
            ui,
            entry,
            input_rect,
            theme,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            variants,
            value,
        ),
        PropertyKind::Text(text) => variants::render_text_input(
            ui,
            entry,
            input_rect,
            theme,
            sp,
            flat_style,
            actor_label,
            commands,
            keyframe_mode,
            row_height,
            text,
        ),
    }
}
