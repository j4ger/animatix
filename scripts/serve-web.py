#!/usr/bin/env python3
"""Local static server for the Animatix web demo with production-like serving:

- correct `application/wasm` MIME type (enables instantiateStreaming)
- transparent brotli negotiation: serves the precompressed `.br` twin when
  the client advertises `Accept-Encoding: br` (a CDN does the same)
- cache headers that keep the edit-and-reload loop working: generated engine
  artifacts (`.wasm`, `pkg*/**.js`) are cacheable in production mode, while
  pages, stylesheets and `.amx` scene sources must be revalidated.
- `--no-cache` mode (default in local dev): sends no-cache headers for all
  resources so rebuilds and edits take effect immediately without clearing browser cache.
- staleness detection: checks if `web/pkg` wasm binary is older than `crates/`
  engine sources and warns loudly on startup and via HTTP headers.

Usage:
  python3 scripts/serve-web.py [port] [root] [--cache] [--no-cache]
  (default port 8124, serves web/, no-cache default)
"""
import argparse
import http.server
import json
import os
import subprocess
import sys

def find_default_web_dir():
    env_root = os.environ.get("SERVE_ROOT")
    if env_root and os.path.isdir(env_root):
        return os.path.abspath(env_root)

    # Check git root if available
    try:
        git_root = subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"],
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
        candidate = os.path.join(git_root, "web")
        if os.path.isdir(candidate):
            return candidate
    except Exception:
        pass

    script_dir = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.normpath(os.path.join(script_dir, "..", "web"))
    if os.path.isdir(candidate):
        return candidate

    if os.path.isdir("web"):
        return os.path.abspath("web")
    if os.path.isfile("index.html") and os.path.isdir("scenes"):
        return os.path.abspath(".")

    return os.path.abspath("web")


WEB_DIR = find_default_web_dir()
REPO_ROOT = os.path.dirname(WEB_DIR) if os.path.basename(WEB_DIR) == "web" else os.path.abspath(".")

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".wasm": "application/wasm",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".amx": "text/plain; charset=utf-8",
    ".ttf": "font/ttf",
    ".otf": "font/otf",
}

# Generated by scripts/build-web.sh: expensive to rebuild, safe to cache in prod.
CACHEABLE = ".wasm"

NO_CACHE_MODE = True
WASM_STALENESS = None


def check_wasm_staleness(web_dir):
    """Check if web/pkg wasm files are missing or older than crates/ engine source."""
    repo_root = None
    try:
        repo_root = subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=web_dir if os.path.isdir(web_dir) else None,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except Exception:
        pass

    if not repo_root or not os.path.isdir(repo_root):
        repo_root = os.path.dirname(os.path.abspath(web_dir))

    crates_dir = os.path.join(repo_root, "crates")
    if not os.path.isdir(crates_dir):
        return None

    try:
        out = subprocess.check_output(
            ["git", "log", "-1", "--format=%ct|%h|%s", "crates/"],
            cwd=repo_root,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
        parts = out.split("|", 2)
        crates_ts = int(parts[0])
        crates_hash = parts[1]
        crates_msg = parts[2]
    except Exception:
        return None

    results = []
    for pkg_name in ("pkg", "pkg-slim"):
        pkg_dir = os.path.join(web_dir, pkg_name)
        wasm = os.path.join(pkg_dir, "animatix_web_bg.wasm")
        if not os.path.isfile(wasm):
            results.append((pkg_name, "missing", 0))
        else:
            mtime = os.path.getmtime(wasm)
            if crates_ts > mtime:
                results.append((pkg_name, "stale", mtime))
            else:
                results.append((pkg_name, "fresh", mtime))

    return {
        "crates_ts": crates_ts,
        "crates_hash": crates_hash,
        "crates_msg": crates_msg,
        "results": results,
    }


def cache_control(path):
    if NO_CACHE_MODE:
        return "no-cache, no-store, must-revalidate"
    generated = (
        path.endswith(CACHEABLE)
        or "/pkg" in path.replace(os.sep, "/")
        or path.endswith(".wasm.br")
    )
    if generated:
        return "public, max-age=300"
    return "no-cache"


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=WEB_DIR, **kwargs)

    def guess_type(self, path):
        ext = os.path.splitext(path)[1].lower()
        return MIME.get(ext, "application/octet-stream")

    def translate_path(self, path):
        clean_path = path.split("?")[0].split("#")[0]
        if clean_path.startswith("/dogfood/"):
            rel = clean_path.lstrip("/").replace("/", os.sep)
            return os.path.join(REPO_ROOT, rel)
        if clean_path in ("/arena", "/arena/"):
            return os.path.join(WEB_DIR, "arena", "index.html")

        translated = super().translate_path(path)
        # Transparently serve web/embed/src/amx-player.js when embed/amx-player.js is requested,
        # so local dev does not require a prebuilt bundle and live edits take effect immediately.
        if translated.endswith(os.path.join("embed", "amx-player.js")):
            src_candidate = os.path.join(os.path.dirname(translated), "src", "amx-player.js")
            if os.path.isfile(src_candidate):
                if not os.path.exists(translated) or os.path.getmtime(src_candidate) > os.path.getmtime(translated):
                    return src_candidate
        return translated

    def do_GET(self):
        clean_path = self.path.split("?")[0]
        if clean_path == "/api/arena/battles":
            battles_dir = os.path.join(REPO_ROOT, "dogfood", "arena", "battles")
            battles = []
            if os.path.isdir(battles_dir):
                for entry in sorted(os.listdir(battles_dir)):
                    entry_dir = os.path.join(battles_dir, entry)
                    if os.path.isdir(entry_dir):
                        battle_json = os.path.join(entry_dir, "battle.json")
                        title = entry
                        tags = []
                        if os.path.isfile(battle_json):
                            try:
                                with open(battle_json, "r", encoding="utf-8") as f:
                                    data = json.load(f)
                                    title = data.get("title", entry)
                                    tags = data.get("tags", [])
                            except Exception:
                                pass
                        battles.append({"id": entry, "title": title, "tags": tags})
            payload = json.dumps(battles).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(payload)))
            self.send_header("Cache-Control", "no-cache")
            self.end_headers()
            self.wfile.write(payload)
            return

        if clean_path.startswith("/api/arena/battle/"):
            battle_id = clean_path[len("/api/arena/battle/"):].strip("/")
            battle_json = os.path.join(REPO_ROOT, "dogfood", "arena", "battles", battle_id, "battle.json")
            if os.path.isfile(battle_json):
                with open(battle_json, "rb") as f:
                    content = f.read()
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(content)))
                self.send_header("Cache-Control", "no-cache")
                self.end_headers()
                self.wfile.write(content)
                return
            else:
                self.send_error(404, "Battle not found")
                return

        return super().do_GET()

    def do_POST(self):
        clean_path = self.path.split("?")[0]
        if clean_path == "/api/arena/vote":
            content_len = int(self.headers.get("Content-Length", 0))
            raw = self.rfile.read(content_len)
            try:
                data = json.loads(raw.decode("utf-8"))
                battle_id = data.get("battle_id")
                if not battle_id:
                    self.send_error(400, "Missing battle_id")
                    return
                battle_dir = os.path.join(REPO_ROOT, "dogfood", "arena", "battles", battle_id)
                os.makedirs(battle_dir, exist_ok=True)
                feedback_file = os.path.join(battle_dir, "feedback.json")
                with open(feedback_file, "w", encoding="utf-8") as f:
                    json.dump(data, f, indent=2)

                arena_dir = os.path.join(REPO_ROOT, "dogfood", "arena")
                os.makedirs(arena_dir, exist_ok=True)
                history_file = os.path.join(arena_dir, "feedback.jsonl")
                with open(history_file, "a", encoding="utf-8") as f:
                    f.write(json.dumps(data) + "\n")

                resp = json.dumps({"status": "ok"}).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(resp)))
                self.end_headers()
                self.wfile.write(resp)
                return
            except Exception as e:
                self.send_error(500, str(e))
                return

        self.send_error(404, "Unknown endpoint")

    def send_head(self):
        # brotli negotiation: prefer the precompressed twin when present
        path = self.translate_path(self.path)
        accepts_br = "br" in self.headers.get("Accept-Encoding", "")
        if accepts_br and os.path.isfile(path) and not path.endswith(".br"):
            br_path = path + ".br"
            if os.path.isfile(br_path):
                # serve file.br with the original's type + Content-Encoding
                f = open(br_path, "rb")
                try:
                    self.send_response(200)
                    self.send_header("Content-Type", self.guess_type(path))
                    self.send_header("Content-Encoding", "br")
                    self.send_header("Content-Length", str(os.fstat(f.fileno()).st_size))
                    self.send_header("Vary", "Accept-Encoding")
                    self.end_headers()
                    return f
                except Exception:
                    f.close()
                    raise
        return super().send_head()

    def end_headers(self):
        self.send_header("Cache-Control", cache_control(self.translate_path(self.path)))
        # Attach staleness header if WASM artifacts are out-of-date
        if WASM_STALENESS and any(s == "stale" for _, s, _ in WASM_STALENESS["results"]):
            if "/pkg" in self.path:
                self.send_header("X-Animatix-Wasm-Stale", "true")
        super().end_headers()

    def log_message(self, fmt, *args):
        sys.stderr.write("[serve-web] %s\n" % (fmt % args))


def print_staleness_banner(staleness):
    stale_items = [name for name, status, _ in staleness["results"] if status == "stale"]
    missing_items = [name for name, status, _ in staleness["results"] if status == "missing"]
    if not stale_items and not missing_items:
        return

    import datetime
    crates_dt = datetime.datetime.fromtimestamp(staleness["crates_ts"])
    print("\n" + "=" * 72, file=sys.stderr)
    if missing_items:
        print(f"⚠️  WARNING: WASM package(s) missing: {', '.join(missing_items)}", file=sys.stderr)
    if stale_items:
        print(f"⚠️  WARNING: web/pkg wasm binary is older than crates/ engine source!", file=sys.stderr)
        print(f"   Stale packages: {', '.join(stale_items)}", file=sys.stderr)
        print(f"   Latest engine:  {crates_dt.strftime('%Y-%m-%d %H:%M:%S')} [{staleness['crates_hash']}]", file=sys.stderr)
        print(f"   Scenes using newer syntax (e.g. 'settle-in') may fail in browser.", file=sys.stderr)
    print(f"   To rebuild quickly:", file=sys.stderr)
    print(f"     scripts/ensure-web-pkg.sh --dev", file=sys.stderr)
    print("=" * 72 + "\n", file=sys.stderr)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Animatix local web server")
    parser.add_argument("port", nargs="?", type=int, default=8124, help="Port (default: 8124)")
    parser.add_argument("root", nargs="?", type=str, default=None, help="Root directory (default: web/)")
    parser.add_argument("--cache", action="store_true", help="Enable 5-min caching for .wasm (production simulation)")
    parser.add_argument("--no-cache", action="store_true", help="Disable caching for all files (default)")

    args = parser.parse_args()

    port = args.port
    if args.root:
        if os.path.isdir(args.root):
            WEB_DIR = os.path.abspath(args.root)
        else:
            fallback = find_default_web_dir()
            WEB_DIR = fallback if os.path.isdir(fallback) else os.path.abspath(args.root)
    else:
        WEB_DIR = find_default_web_dir()

    # By default, use no-cache unless --cache is explicitly set
    NO_CACHE_MODE = not args.cache

    WASM_STALENESS = check_wasm_staleness(WEB_DIR)
    if WASM_STALENESS:
        print_staleness_banner(WASM_STALENESS)

    cache_desc = "disabled (live reload mode)" if NO_CACHE_MODE else "enabled (max-age=300 for wasm)"
    print(f"serving {WEB_DIR} at http://127.0.0.1:{port}/ [caching: {cache_desc}]")

    server = http.server.ThreadingHTTPServer(("127.0.0.1", port), Handler)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
