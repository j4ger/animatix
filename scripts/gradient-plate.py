#!/usr/bin/env python3
"""Generate the Gradient walkthrough from its canonical standalone acts."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
HERE = ROOT / "web/demos/gradient"
ACTS = [("losssurface", "LossSurface"), ("gradientdirection", "GradientDirection"),
        ("descent", "Descent"), ("learningrate", "LearningRate")]


def build():
    chunks = ['''// GENERATED by scripts/gradient-plate.py; edit the standalone acts instead.
// --set does not propagate into compositions: this walkthrough uses defaults.
// Individual figures on the page receive the interactive parameter overrides.
import "../../../examples/lib/theme.amx"
import "../../../examples/lib/stage.amx"
config { colorscheme: "ember", resolution: (1280, 720) }
''']
    for index, (name, label) in enumerate(ACTS):
        source = (HERE / (name + ".amx")).read_text()
        config = re.search(r'^config \{[^\n]+\}', source, re.M)
        if not config:
            raise ValueError(f"missing one-line config: {name}")
        body = source[config.start():]
        body = re.sub(r', resolution: \(1280, 720\)', '', body, count=1)
        chunks.append(f"\n// Canonical source: {name}.amx\n# {label}\n" + body.rstrip() + "\n")
        if index + 1 < len(ACTS):
            chunks.append(f"\nplay {ACTS[index + 1][1]} [wipe-left, 420ms]\n")
    return "".join(chunks)


def main():
    path = HERE / "scene.amx"
    generated = build()
    if "--check" in sys.argv:
        if path.read_text() != generated:
            raise SystemExit("Gradient plate stale: run python3 scripts/gradient-plate.py")
        print("Gradient plate matches its four canonical acts")
    else:
        path.write_text(generated)


if __name__ == "__main__":
    main()
